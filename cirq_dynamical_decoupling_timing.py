import cirq
import time

qubits_per_layer = [[cirq.GridQubit(5, 9),
  cirq.GridQubit(6, 9),
  cirq.GridQubit(5, 10),
  cirq.GridQubit(6, 8)],
 [cirq.GridQubit(8, 8),
  cirq.GridQubit(6, 9),
  cirq.GridQubit(7, 9),
  cirq.GridQubit(5, 10),
  cirq.GridQubit(6, 10),
  cirq.GridQubit(7, 8)],
 [cirq.GridQubit(6, 9),
  cirq.GridQubit(7, 9),
  cirq.GridQubit(6, 10),
  cirq.GridQubit(7, 8)],
 [cirq.GridQubit(5, 9),
  cirq.GridQubit(6, 9),
  cirq.GridQubit(6, 8),
  cirq.GridQubit(7, 8)]]

all_qubits = set()
for qubits in qubits_per_layer:
    for q in qubits:
        all_qubits.add(q)



layers_grid_qubit_pairs = [[(cirq.GridQubit(5, 9), cirq.GridQubit(5, 10)),
  (cirq.GridQubit(6, 8), cirq.GridQubit(6, 9))],
 [(cirq.GridQubit(5, 10), cirq.GridQubit(6, 10)),
  (cirq.GridQubit(6, 9), cirq.GridQubit(7, 9)),
  (cirq.GridQubit(7, 8), cirq.GridQubit(8, 8))],
 [(cirq.GridQubit(6, 9), cirq.GridQubit(6, 10)),
  (cirq.GridQubit(7, 8), cirq.GridQubit(7, 9))],
 [(cirq.GridQubit(5, 9), cirq.GridQubit(6, 9)),
  (cirq.GridQubit(6, 8), cirq.GridQubit(7, 8))]]

def make_fake_trotter_circuit(num_cycles: int):
    moments = []
    for layer, qubits in zip(layers_grid_qubit_pairs, qubits_per_layer):
        moments.append(cirq.Moment((cirq.Y**0.3)(qubit)) for qubit in qubits)
        moments.append(cirq.Moment( cirq.CZ(*pair) for pair in layer))
    return cirq.Circuit.from_moments(*moments)*num_cycles + cirq.Moment(cirq.M(*all_qubits))


def time_sweep(num_cycles: int, num_circuits: int):
    t1 = time.time()
    circuit = make_fake_trotter_circuit(num_cycles)
    t2 = time.time()
    print(f'Generating initial circuit took {t2-t1} s')
    t1 = time.time()
    circuit_sweep, sweep_params = cirq.transformers.gauge_compiling.CZGaugeTransformer.as_sweep(circuit, N = num_circuits)
    t2 = time.time()
    print(f'Gauge compiling took {t2-t1} s')
    t1 = time.time()
    circuit_sweep, sweep_params = cirq.merge_single_qubit_gates_to_phxz_symbolized(circuit_sweep, sweep=sweep_params)
    t2 = time.time()
    assert len(sweep_params) > 0
    print(f'Merging gates took {t2-t1} s')
    t1 = time.time()
    circuit_sweep = cirq.add_dynamical_decoupling(circuit_sweep)
    t2 = time.time()
    print(f'Adding DD took {t2-t1} s')

def time_batch(num_cycles: int, num_circuits: int):
    t1 = time.time()
    circuit = make_fake_trotter_circuit(num_cycles)
    t2 = time.time()
    print(f'Generating initial circuit took {t2-t1} s')
    t1 = time.time()
    circuits_batch = [cirq.transformers.gauge_compiling.cz_gauge.CZGaugeTransformer(circuit) for _ in range(num_circuits)]
    t2 = time.time()
    print(f'Gauge compiling took {t2-t1} s')
    t1 = time.time()
    circuits_batch = [cirq.merge_single_qubit_moments_to_phxz(circuit) for circuit in circuits_batch]
    t2 = time.time()
    print(f'Merging gates took {t2-t1} s')
    t1 = time.time()
    circuits_batch = [cirq.add_dynamical_decoupling(circuit) for circuit in circuits_batch]
    t2 = time.time()
    print(f'Adding DD took {t2-t1} s')

if __name__ == "__main__":
    print(">>> time_sweep(50, 100)")
    time_sweep(50, 100)
    print()
    print(">>> time_batch(50, 100)")
    time_batch(50, 100)
